-- Cozinha Toca — captura das contagens que chegam pelo grupo do WhatsApp.
-- Aditivo, idempotente (roda 2x sem quebrar). Sem RLS pra anon/authenticated —
-- só o backend (service_role) grava e lê, mesmo padrão de porcionamento_config.

create table if not exists cozinha_diario (
  id                bigint generated by default as identity primary key,
  tenant_id         bigint,
  data              date not null,
  item              text not null,
  detalhe           text,
  valor             numeric not null,
  unidade           text not null,
  remetente         text,
  mensagem_original text not null,
  criado_em         timestamptz not null default now()
);

create index if not exists cozinha_diario_data_item_idx
  on cozinha_diario (data, item);

alter table cozinha_diario enable row level security;
revoke all on cozinha_diario from anon, authenticated;
