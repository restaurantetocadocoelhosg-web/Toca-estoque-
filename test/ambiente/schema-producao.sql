create table if not exists tenants (
  id bigint generated by default as identity not null,
  nome text not null,
  slug text not null,
  cnpj text,
  telefone text,
  endereco text,
  plano text default 'financeiro'::text not null,
  config jsonb default '{}'::jsonb not null,
  ativo boolean default true not null,
  suspenso_em timestamp with time zone,
  criado_em timestamp with time zone default now() not null,
  primary key (id),
  unique (slug),
  constraint tenants_plano_check CHECK ((plano = ANY (ARRAY['financeiro'::text, 'estoque'::text, 'completo'::text])))
);

create table if not exists users (
  id bigserial not null,
  username text not null,
  nome text not null,
  role text not null,
  password_hash text not null,
  active integer default 1 not null,
  created_at timestamp with time zone default now(),
  updated_at timestamp with time zone default now(),
  permissoes jsonb,
  tenant_id bigint,
  primary key (id),
  unique (username),
  constraint users_role_check CHECK ((role = ANY (ARRAY['admin'::text, 'gerente'::text, 'operador'::text, 'superadmin'::text])))
);

create table if not exists whatsapp_grupos (
