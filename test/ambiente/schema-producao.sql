create table if not exists audit_logs (
  id bigserial not null,
  usuario_id bigint,
  usuario_nome text,
  role text,
  acao text not null,
  detalhes text,
  ip text,
  created_at timestamp with time zone default now(),
  tenant_id bigint not null,
  primary key (id)
);

