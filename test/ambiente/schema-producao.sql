create table if not exists porcionamento_config (
  id bigint generated by default as identity not null,
  tenant_id bigint,
  item text not null,
  pesos_g int4[] default '{}'::integer[] not null,
  unidade text default 'bolas'::text not null,
  ordem integer default 0 not null,
  ativo boolean default true not null,
  criado_em timestamp with time zone default now() not null,
  atualizado_em timestamp with time zone default now() not null,
  atualizado_por text,
  primary key (id)
);
create unique index if not exists porcionamento_config_tenant_item on porcionamento_config USING btree (COALESCE(tenant_id, (0)::bigint), lower(item));

